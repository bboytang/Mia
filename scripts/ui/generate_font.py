#!/usr/bin/env python3
"""Generate the flash-resident 16px/2bpp UI subset; requires lv_font_conv 1.5.3."""
import argparse
import hashlib
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
BOARD = ROOT / 'main/boards/folotoy/ai-passport'


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('font', type=Path, help='NotoSansCJKsc-Regular.otf, see docs/Youmi-ui/IMPLEMENTATION.md')
    p.add_argument('converter', help='lv_font_conv executable')
    args = p.parse_args()
    text = ''.join((BOARD / f).read_text() for f in ['youmi_ui_draw.h', 'youmi_display.cc'])
    text += (ROOT / 'main/assets/locales/zh-CN/language.json').read_text()
    text += (ROOT / 'main/passport/private_authorization.cc').read_text()
    symbols = ''.join(sorted(set(c for c in text if ord(c) > 127)))
    output = BOARD / 'youmi_ui_font.c'
    subprocess.run([args.converter, '--size', '16', '--bpp', '2', '--format', 'lvgl',
                    '--font', str(args.font), '-r', '32-126', '--symbols', symbols,
                    '--no-compress', '--no-kerning', '--lv-font-name', 'youmi_ui_font',
                    '--lv-include', 'lvgl.h', '-o', str(output)], check=True)
    source = output.read_text()
    start = source.index(' * Opts:')
    end = source.index('\n', start)
    source = source[:start] + ' * Generated by scripts/ui/generate_font.py; Noto CJK, SIL OFL 1.1.' + source[end:]
    output.write_text(source.rstrip() + "\n")
    print('Source font SHA256:', hashlib.sha256(args.font.read_bytes()).hexdigest())


if __name__ == '__main__':
    main()
